"""Generates the search folding tables of engine/text/src/SearchFold.cpp.

Usage: python tools/textc/gen_search_fold.py > folded.inc, then paste the arrays into SearchFold.cpp.

Folding removes case and diacritics so that search ignores both: a character becomes its base letter in
lowercase (NFD decomposition without combining marks, then casefold). Letters that do not decompose get an
explicit fold (Ł -> l, ı -> i, ß -> ss, ...). Tables cover Latin-1 Supplement and Latin Extended-A
(U+00C0..U+017F, folded to ASCII, one or two letters) and Greek and Cyrillic (U+0370..U+04FF, folded to one
code point of the same script).
"""

import sys
import unicodedata

LATIN_SPECIAL = {
    0x00C6: "ae", 0x00E6: "ae", 0x00D0: "d", 0x00F0: "d", 0x00D8: "o", 0x00F8: "o",
    0x00DE: "th", 0x00FE: "th", 0x00DF: "ss", 0x0110: "d", 0x0111: "d", 0x0126: "h", 0x0127: "h",
    0x0130: "i", 0x0131: "i", 0x0132: "ij", 0x0133: "ij", 0x0138: "k", 0x013F: "l", 0x0140: "l",
    0x0141: "l", 0x0142: "l", 0x0149: "n", 0x014A: "n", 0x014B: "n", 0x0152: "oe", 0x0153: "oe",
    0x0166: "t", 0x0167: "t", 0x017F: "s",
}


def base_letter(c: str) -> str:
    decomposed = unicodedata.normalize("NFD", c)
    stripped = "".join(ch for ch in decomposed if not unicodedata.combining(ch))
    return stripped.casefold()


def latin_table():
    entries = []
    for cp in range(0x00C0, 0x0180):
        if cp in LATIN_SPECIAL:
            entries.append(LATIN_SPECIAL[cp])
            continue
        folded = base_letter(chr(cp))
        if folded.isascii() and folded.isalpha() and 1 <= len(folded) <= 2:
            entries.append(folded)
        else:
            entries.append("")  # kept as it is (× and ÷)
    return entries


def script_table(first: int, last: int):
    entries = []
    for cp in range(first, last + 1):
        c = chr(cp)
        if unicodedata.category(c) == "Cn":
            entries.append(0)
            continue
        folded = base_letter(c)
        if len(folded) == 1 and ord(folded) != cp and first <= ord(folded) <= last:
            entries.append(ord(folded))
        else:
            entries.append(0)  # kept as it is
    return entries


def main():
    out = sys.stdout
    out.write(f"// Generated by tools/textc/gen_search_fold.py (Unicode {unicodedata.unidata_version}).\n")
    out.write("constexpr std::array<std::string_view, 0x180 - 0xC0> kLatinFolds = {\n")
    latin = latin_table()
    for i in range(0, len(latin), 12):
        row = ", ".join(f'"{e}"' for e in latin[i:i + 12])
        out.write(f"    {row}, // U+{0xC0 + i:04X}\n")
    out.write("};\n\n")
    greek_cyrillic = script_table(0x0370, 0x04FF)
    out.write("constexpr std::array<char16_t, 0x500 - 0x370> kGreekCyrillicFolds = {\n")
    for i in range(0, len(greek_cyrillic), 12):
        row = ", ".join(f"0x{e:04X}" for e in greek_cyrillic[i:i + 12])
        out.write(f"    {row}, // U+{0x370 + i:04X}\n")
    out.write("};\n")


if __name__ == "__main__":
    main()
