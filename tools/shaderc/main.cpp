// illusion_shaderc: compiles a material shader at build time into C++ that embeds the cooked ShaderAsset, so
// an engine library carries a built-in material shader (builtin:/shader/standard) compiled like a game's
// shader.
//
//   illusion_shaderc <slangc> <shader library> <source.shader> <virtual path> <namespace> <function>
//   <output.cpp>
//
// The output defines `std::span<const std::byte> <namespace>::<function>() noexcept`, the bytes of
// serializeShader(). Compiler diagnostics are printed as `file:line:column: error: message` lines and fail
// the build.

#include <illusion/assets/ShaderCompiler.hpp>

#include <cstdio>
#include <filesystem>
#include <fstream>
#include <sstream>
#include <string>
#include <string_view>
#include <vector>

using namespace illusion;

namespace
{

std::filesystem::path fromUtf8(std::string_view text)
{
    return std::filesystem::path(std::u8string(reinterpret_cast<const char8_t*>(text.data()), text.size()));
}

bool readText(const std::filesystem::path& path, std::string& out)
{
    std::ifstream file(path, std::ios::binary);
    if (!file)
    {
        return false;
    }
    std::ostringstream buffer;
    buffer << file.rdbuf();
    out = buffer.str();
    return true;
}

std::string embedSource(std::string_view source, std::string_view nameSpace, std::string_view function,
                        const std::vector<std::byte>& bytes)
{
    std::string text = "// Generated by illusion_shaderc from ";
    text += source;
    text += "; do not edit.\n\n#include <cstddef>\n#include <span>\n\nnamespace\n{\nalignas(4) constexpr "
            "unsigned char "
            "kShader[] = {";
    static constexpr char kHex[] = "0123456789abcdef";
    for (std::size_t i = 0; i < bytes.size(); ++i)
    {
        text += i % 16 == 0 ? "\n    " : " ";
        const auto value = std::to_integer<unsigned>(bytes[i]);
        text += "0x";
        text += kHex[value >> 4];
        text += kHex[value & 15];
        text += ',';
    }
    text += "\n};\n} // namespace\n\nnamespace ";
    text += nameSpace;
    text += "\n{\n\nstd::span<const std::byte> ";
    text += function;
    text += "() noexcept\n{\n    return std::as_bytes(std::span<const unsigned char>(kShader));\n}\n\n} // "
            "namespace ";
    text += nameSpace;
    text += "\n";
    return text;
}

int run(const std::vector<std::string>& arguments)
{
    if (arguments.size() != 7)
    {
        std::fprintf(stderr,
                     "usage: illusion_shaderc <slangc> <shader library> <source.shader> <virtual path> "
                     "<namespace> <function> <output.cpp>\n");
        return 2;
    }
    const std::string_view sourcePath = arguments[2];
    const std::string_view virtualPath = arguments[3];
    Expected<ShaderCompiler, std::string> compiler = ShaderCompiler::create(
        ShaderCompilerDesc{.slangc = fromUtf8(arguments[0]), .library = fromUtf8(arguments[1])});
    if (!compiler)
    {
        std::fprintf(stderr, "illusion_shaderc: %s\n", compiler.error().c_str());
        return 1;
    }
    std::string source;
    if (!readText(fromUtf8(sourcePath), source))
    {
        std::fprintf(stderr, "illusion_shaderc: cannot read %s\n", arguments[2].c_str());
        return 1;
    }
    const ShaderCompileResult result = compiler->compile(virtualPath, source);
    for (const ShaderDiagnostic& diagnostic : result.diagnostics)
    {
        std::fprintf(stderr, "%s\n", formatShaderDiagnostic(diagnostic).c_str());
    }
    if (!result.shader)
    {
        std::fprintf(stderr, "illusion_shaderc: %s does not compile\n", arguments[2].c_str());
        return 1;
    }
    const std::string text =
        embedSource(virtualPath, arguments[4], arguments[5], serializeShader(*result.shader));
    const std::filesystem::path output = fromUtf8(arguments[6]);
    std::error_code code;
    std::filesystem::create_directories(output.parent_path(), code);
    std::ofstream file(output, std::ios::binary);
    file.write(text.data(), static_cast<std::streamsize>(text.size()));
    if (!file)
    {
        std::fprintf(stderr, "illusion_shaderc: cannot write %s\n", arguments[6].c_str());
        return 1;
    }
    return 0;
}

} // namespace

#if defined(_WIN32)
// Windows passes narrow arguments in the ANSI code page, which cannot hold every path; take the UTF-16 ones.
int wmain(int argc, wchar_t** argv)
{
    std::vector<std::string> arguments;
    for (int i = 1; i < argc; ++i)
    {
        const std::u8string text = std::filesystem::path(argv[i]).u8string();
        arguments.emplace_back(reinterpret_cast<const char*>(text.data()), text.size());
    }
    return run(arguments);
}
#else
int main(int argc, char** argv)
{
    return run(std::vector<std::string>(argv + 1, argv + argc));
}
#endif
